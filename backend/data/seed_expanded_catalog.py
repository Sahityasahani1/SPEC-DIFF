def make_search_url(retailer: str, query: str) -> str:
    q = quote_plus(query.strip())
    r = retailer.lower()
    if "flipkart" in r:
        return f"https://www.flipkart.com/search?q={q}"
    elif "croma" in r:
        return f"https://www.croma.com/searchB?q={q}"
    elif "reliance" in r:
        return f"https://www.reliancedigital.in/search?q={q}"
    elif "apple" in r:
        return "https://www.apple.com/in/shop/buy-iphone"
    return f"https://www.amazon.in/s?k={q}"

