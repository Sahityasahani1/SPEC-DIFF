# Filter out duplicates
added_count = 0
for sku in new_skus:
    if sku["id"] not in existing_ids:
        existing_skus.append(sku)
        existing_ids.add(sku["id"])
        added_count += 1

print(f"[INFO] Appended {added_count} new unique items. Total catalog size: {len(existing_skus)}")

# Write updated CSV
headers = list(existing_skus[0].keys())
with open(CSV_PATH, mode="w", encoding="utf-8", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=headers)
    writer.writeheader()
    for row in existing_skus:
        writer.writerow(row)

